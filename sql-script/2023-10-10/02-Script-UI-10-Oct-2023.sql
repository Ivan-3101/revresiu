CREATE TABLE IF NOT EXISTS ui.profileparamsconfig
(
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 ),
    workflowid integer,
    parametername character varying COLLATE pg_catalog."default",
    type character varying COLLATE pg_catalog."default",
    CONSTRAINT profileparamsconfig_pkey PRIMARY KEY (id),
    CONSTRAINT workflowid FOREIGN KEY (workflowid)
        REFERENCES ui.workflowmasters (workflowid) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
        NOT VALID
);

